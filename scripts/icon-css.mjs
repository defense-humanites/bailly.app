// Writes `app/assets/css/icons.css`: the CSS of every icon in Nuxt Icon's
// client bundle (the icons found in the sources, cf. `nuxt.config.ts`), as
// Nuxt Icon would write it in the page (same selectors, layer and format).
// Served with the application's style sheet, an icon rendered only on the
// client no longer adds a style sheet to the page, which made the browser
// recompute the whole page's style (cf. `claude/audit-inp.md`).
// Run after `nuxi prepare` (or a build) whenever an icon is added; a unit
// test checks that none is missing.
import { writeFileSync } from "node:fs";
import { getIconCSS } from "@iconify/utils/lib/css/icon";
import { init } from "../.nuxt/nuxt-icon-client-bundle.mjs";

const escape = selector => selector.replace(/([^\w-])/g, "\\$1");
const rules = [];
init((name, icon) => {
  rules.push(getIconCSS(icon, { iconSelector: `:where(.${escape(`i-${name}`)})`, format: "compressed" }));
});
rules.sort();
writeFileSync(
  new URL("../app/assets/css/icons.css", import.meta.url),
  `/* Generated by scripts/icon-css.mjs: do not edit. */\n@layer base {\n${rules.join("\n")}\n}\n`,
);
console.log(`${rules.length} icons`);
