/**
 * Acquires the Morpheus stem data (Alpheios dataset, Greek) into `morpheus-data/`
 * (ignored by git), through `@libmorpheus/node/data` (pinned revision, verified
 * digests; no Deno nor C toolchain needed), then generates the manifest that bundles
 * its runtime subset into the Worker (`src/morpheus/stemlib-manifest.mjs`: one Data
 * module import per file, cf. the `rules` of `wrangler.jsonc`).
 *
 * Usage: `pnpm run morpheus:data [--force]`. The data is kept if already there
 * (its receipt, `MORPHEUS-DATA.json`, records the revision); `--force` acquires it
 * again. Required before `pnpm start`, the tests and `wrangler deploy` (the Worker
 * build runs it).
 */

import { acquireMorpheusData } from "@libmorpheus/node/data";
import { existsSync } from "node:fs";
import { readdir, rm, writeFile } from "node:fs/promises";
import { join, posix, relative, sep } from "node:path";
import { isRuntimeFile, LANGUAGE_DIRECTORY } from "../src/morpheus/stemlib.ts";

const DATA_PATH = process.env.MORPHEUS_DATA_PATH?.trim() || "morpheus-data";
const MANIFEST_PATH = "src/morpheus/stemlib-manifest.mjs";
const force = process.argv.includes("--force");

if (force && existsSync(DATA_PATH)) {
  await rm(DATA_PATH, { recursive: true });
}

if (existsSync(join(DATA_PATH, "MORPHEUS-DATA.json"))) {
  console.info(`${DATA_PATH}: stem data already acquired (use --force to renew).`);
} else {
  console.info(`⏳ Acquiring the Alpheios stem data into ${DATA_PATH}...`);
  const receipt = await acquireMorpheusData({ dataset: "alpheios", output: DATA_PATH });
  console.info(
    `✅ ${receipt.files.count} files (${receipt.source.repository} @ ` +
      `${receipt.source.revision.slice(0, 7)}).`
  );
}

// The manifest: the runtime subset of the language tree, as `[path, bytes]`.
const languageDirectory = join(DATA_PATH, LANGUAGE_DIRECTORY);
const files: string[] = [];

for (
  const entry of await readdir(languageDirectory, { recursive: true, withFileTypes: true })
) {
  if (!entry.isFile()) continue;
  const relativePath = relative(languageDirectory, join(entry.parentPath, entry.name))
    .split(sep).join("/");
  if (isRuntimeFile(relativePath)) files.push(relativePath);
}

files.sort();

const manifestDirectory = posix.dirname(MANIFEST_PATH);
const importPath = (relativePath: string) =>
  posix.relative(
    manifestDirectory,
    posix.join(DATA_PATH.split(sep).join("/"), LANGUAGE_DIRECTORY, relativePath)
  );

const lines = [
  "// Generated by `pnpm run morpheus:data`: do not edit.",
  "//",
  "// The runtime subset of the Greek stem data, bundled into the Worker as Data",
  "// modules (cf. the `rules` of `wrangler.jsonc`), for `WasmLemmatizer`.",
  "// `morpheus-data/` is ignored by git: run the script before building the Worker.",
  "",
  ...files.map((file, index) => `import f${index} from "${importPath(file)}";`),
  "",
  "/** @type {[string, ArrayBuffer][]} */",
  "export const stemlibEntries = [",
  ...files.map((file, index) =>
    `  ["${LANGUAGE_DIRECTORY}/${file}", f${index}]${index < files.length - 1 ? "," : ""}`
  ),
  "];",
  ""
];

await writeFile(MANIFEST_PATH, lines.join("\n"));
console.info(`✅ ${MANIFEST_PATH}: ${files.length} data modules.`);
